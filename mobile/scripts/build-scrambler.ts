/**
 * Bundles the scrambler (scrambler/, WebAssembly inlined in base64) and the cross solutions into one self-contained
 * HTML page. The app loads it in a hidden WebView: Hermes has no WebAssembly.
 */
import { resolve } from "node:path";
import { mkdir, writeFile } from "node:fs/promises";

const repo = resolve(import.meta.dir, "../..");
const wasm = await Bun.file(resolve(repo, "scrambler/scrambler.wasm")).bytes();
const result = await Bun.build({
  entrypoints: [resolve(import.meta.dir, "scrambler-entry.ts")], target: "browser", format: "iife", minify: true, splitting: false,
  define: { CUBIX_SCRAMBLER_WASM: JSON.stringify(Buffer.from(wasm).toString("base64")) },
});
if (!result.success) { console.error(result.logs.join("\n")); process.exit(1); }
const js = await result.outputs[0].text();
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"></head><body><script>${js.replace(/<\/script>/g, "<\\/script>")}</script></body></html>`;
const out = resolve(import.meta.dir, "../src/scrambler/scrambler-html.ts");
await mkdir(resolve(import.meta.dir, "../src/scrambler"), { recursive: true });
const hash = new Bun.CryptoHasher("sha256").update(wasm).digest("hex").slice(0, 8);
await writeFile(out, `// Generated by scripts/build-scrambler.ts from scrambler/scrambler.wasm (${hash}). Do not edit.\nexport const SCRAMBLER_HTML = ${JSON.stringify(html)};\n`);
// The browser build runs the same page as a worker (src/scrambler/index.web.tsx), off the page's thread.
await mkdir(resolve(import.meta.dir, "../public"), { recursive: true });
await writeFile(resolve(import.meta.dir, "../public/scrambler.js"), `self.window=self;self.document={addEventListener(){}};self.ReactNativeWebView={postMessage:m=>self.postMessage(m)};\n${js}`);
console.log(`Wrote ${out} (${(html.length / 1024).toFixed(0)} KB)`);
